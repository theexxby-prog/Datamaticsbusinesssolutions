// Cross-reference: field -> panels that read it.
const usedBy = new Map();
const specFields = new Set(fields.map(f => `${f.table}.${f.field}`));
const unknown = [];
for (const p of PANELS) {
  for (const [table, cols] of p.reads) {
    for (const col of cols) {
      const key = `${table}.${col}`;
      if (!specFields.has(key)) { unknown.push(`${p.slug}: ${key}`); continue; }
      if (!usedBy.has(key)) usedBy.set(key, []);
      usedBy.get(key).push(p.slug);
    }
  }
}
if (unknown.length) {
  console.error('Mapping references fields that are not in the spec:\n  ' + unknown.join('\n  '));
  process.exit(1);
}

const b64 = slug => {
  const p = join(SHOTS, `${slug}.jpg`);
  return existsSync(p) ? `data:image/jpeg;base64,${readFileSync(p).toString('base64')}` : '';
};

