// ─── Database requirements document ──────────────────────────────────────────
// Builds the page shared with the warehouse team: every product panel with a
// screenshot, the tables and fields behind it, the grain those rows must be at,
// and the aggregation the panel performs.
//
// Run scripts/panel-shots.mjs first (it writes .panel-shots/), then:
//   node scripts/db-requirements-doc.mjs
//
// Reads scripts/.panel-shots/*.jpg and a JSON export of the field spec, writes
// a single self-contained HTML file with everything inlined.
//
// Why panel-first rather than field-first: the spec has 222 fields, of which
// roughly a third are ids, foreign keys and timestamps that never render. One
// image per field would be mostly blanks and duplicates. The thing their team
// actually needs from a picture is the grain, and grain is a property of a
// panel, not of a column. The field index at the end restores the field-first
// view without needing 222 images.

